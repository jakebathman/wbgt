    /**
     * Estimated WBGT (°F) from the nearest chart cell, or null when the chart has no value.
     */
    public static function lookup(float $temperature, float $humidity): ?float
    {
        $column = (int) round(($temperature - self::FIRST_TEMPERATURE) / self::TEMPERATURE_STEP);
        $row = (int) round($humidity / 5) * 5;

        if ($column < 0) {
            return null;
        }

        return self::TABLE[$row][$column] ?? null;
    }
